// Deploy a .NET web app as a systemd service — host-level, not Docker, matching the
// existing Rayan app precedent (a .NET service on a 127.0.0.1 port, nginx proxying a
// domain to it). Filed next to nginx.ts so the Nginx page can offer to front one of
// these the moment it appears (see nginx.ts's dotnetApps()).
//
// A publish zip is uploaded once (inspect), extracted to a scratch directory under
// /tmp whose path doubles as the handle the follow-up deploy call moves into /opt —
// the same "upload once, refer to it by a server-side handle after that" shape
// /api/docker/load + /api/docker/deploy already use (there, the handle is the image
// tag `docker load` produced).
import posix from 'node:path/posix';
import { randomUUID } from 'node:crypto';
import { promises as fs } from 'node:fs';
import type { Express, Response } from 'express';
import {
  badRequestRoute,
  need,
  nginxSiteSteps,
  port,
  renderNginxSite,
  RE,
  run,
  runCancellable,
  runOrThrow,
  runSteps,
  str,
  type AsyncRoute,
  type SessionRequest,
  type Step,
  type StepResult,
} from './ops.js';
import { readFile, shellQuote, type SshSession } from './ssh.js';
import { copyFinished, finishTransfer, sftpUpload, startTransfer } from './transfers.js';

const STAGING_RE = /^\/tmp\/ssher-dotnet-[0-9a-f-]+$/;
const UNIT_DIR = '/etc/systemd/system';
export const DOTNET_MARKER = '# Generated by SSHer (dotnet)';

// ------------------------------------------------------------------ helpers

interface RuntimeRef {
  name: string;
  version: string;
}

function parseRuntimes(out: string): RuntimeRef[] {
  return [...out.matchAll(/^(\S+)\s+(\d+\.\d+\.\d+)/gm)].map((m) => ({ name: m[1], version: m[2] }));
}

function versionTuple(v: string): [number, number] {
  const [maj, min] = v.split('.').map(Number);
  return [maj || 0, min || 0];
}

/** Same major, installed minor at least the required minor — not a full replica of
 *  .NET's own roll-forward rules, just enough to tell "roughly compatible" from "not
 *  installed at all", which is all this page promises to check. */
function isCompatible(installed: string, required: string): boolean {
  const [iMaj, iMin] = versionTuple(installed);
  const [rMaj, rMin] = versionTuple(required);
  return iMaj === rMaj && iMin >= rMin;
}

interface RuntimeConfig {
  runtimeOptions?: {
    framework?: RuntimeRef;
    frameworks?: RuntimeRef[];
    includedFrameworks?: RuntimeRef[];
  };
}

/** `null` means self-contained (the publish output bundles its own runtime) or the
 *  config declares nothing recognizable — either way, no external check applies. */
function requiredFramework(cfg: RuntimeConfig): RuntimeRef | null {
  const opts = cfg.runtimeOptions;
  if (!opts || opts.includedFrameworks?.length) return null;
  const candidates = opts.framework ? [opts.framework] : (opts.frameworks ?? []);
  return candidates.find((f) => f.name === 'Microsoft.AspNetCore.App') ?? candidates[0] ?? null;
}

function installCommand(required: RuntimeRef): string {
  const kind = required.name.includes('AspNetCore') ? 'aspnetcore' : 'dotnet';
  const channel = required.version.split('.').slice(0, 2).join('.');
  return (
    `curl -fsSL https://dot.net/v1/dotnet-install.sh -o /tmp/dotnet-install.sh && chmod +x /tmp/dotnet-install.sh && ` +
    `/tmp/dotnet-install.sh --runtime ${kind} --channel ${channel} --install-dir /usr/share/dotnet && ` +
    `ln -sf /usr/share/dotnet/dotnet /usr/bin/dotnet && rm -f /tmp/dotnet-install.sh`
  );
}

/** The one `*.runtimeconfig.json` a normal (non-recursive) publish output has at its
 *  top level — ambiguous with more than one, so this refuses rather than guessing. */
async function findMainDll(session: SshSession, dir: string): Promise<string | null> {
  const out = await run(session, `find ${shellQuote(dir)} -maxdepth 1 -name '*.runtimeconfig.json' -printf '%f\\n' 2>/dev/null`);
  const names = out.stdout.split('\n').map((s) => s.trim()).filter(Boolean);
  if (names.length !== 1) return null;
  return names[0].replace(/\.runtimeconfig\.json$/, '.dll');
}

async function readRuntimeConfig(session: SshSession, dir: string, mainDll: string): Promise<RuntimeConfig | null> {
  const path = posix.join(dir, mainDll.replace(/\.dll$/, '.runtimeconfig.json'));
  const raw = await readFile(session, path).catch(() => null);
  if (!raw) return null;
  try {
    return JSON.parse(raw.toString('utf8')) as RuntimeConfig;
  } catch {
    return null;
  }
}

async function checkRuntime(session: SshSession, dir: string, mainDll: string): Promise<StepResult> {
  const title = 'Check the required .NET runtime';
  const cfg = await readRuntimeConfig(session, dir, mainDll);
  if (!cfg) return { title, ok: false, output: 'Could not read the app’s .runtimeconfig.json.' };

  const required = requiredFramework(cfg);
  if (!required) return { title, ok: true, output: 'Self-contained, or no shared framework declared — nothing external needed.' };

  const out = await run(session, 'command -v dotnet >/dev/null 2>&1 && dotnet --list-runtimes 2>&1 || echo __missing__');
  if (out.stdout.includes('__missing__')) {
    return { title, ok: false, output: `dotnet is not installed on this server. Needs ${required.name} ${required.version}.\n\n${installCommand(required)}` };
  }
  const installed = parseRuntimes(out.stdout);
  const match = installed.find((r) => r.name === required.name && isCompatible(r.version, required.version));
  if (!match) {
    const have = installed.map((r) => `${r.name} ${r.version}`).join(', ') || 'none';
    return { title, ok: false, output: `Needs ${required.name} ${required.version} — installed: ${have}.\n\n${installCommand(required)}` };
  }
  return { title, ok: true, output: `${match.name} ${match.version} ✓` };
}

function renderUnit(opts: { name: string; port: number; dir: string; mainDll: string; env: { key: string; value: string }[] }): string {
  const envLines = opts.env.map((e) => `Environment=${e.key}=${e.value}`).join('\n');
  return `${DOTNET_MARKER} on ${new Date().toISOString()}
# ${opts.name} — .NET app on 127.0.0.1:${opts.port}
[Unit]
Description=${opts.name} (.NET app, deployed by SSHer)
After=network.target

[Service]
Type=simple
WorkingDirectory=${opts.dir}
ExecStart=/usr/bin/dotnet ${posix.join(opts.dir, opts.mainDll)} --urls http://127.0.0.1:${opts.port}
Restart=on-failure
RestartSec=5
${envLines}

[Install]
WantedBy=multi-user.target
`;
}

function parseEnv(raw: unknown): { key: string; value: string }[] {
  const env = (Array.isArray(raw) ? raw : [])
    .map((e: { key?: unknown; value?: unknown }) => ({ key: str(e.key), value: String(e.value ?? '') }))
    .filter((e) => e.key);
  for (const e of env) {
    need(RE.envKey.test(e.key), `Invalid environment variable name: ${e.key}`);
    need(!/[\n\r]/.test(e.value), `${e.key} cannot contain a line break`);
  }
  return env;
}

async function cleanupOldStaging(session: SshSession): Promise<void> {
  await run(session, `find /tmp -maxdepth 1 -name 'ssher-dotnet-*' -mmin +60 -exec rm -rf {} + 2>/dev/null`).catch(() => {});
}

// ------------------------------------------------------------------- routes

export function registerDotnet(
  app: Express,
  requireSession: import('express').RequestHandler,
  asyncRoute: AsyncRoute,
  upload: { single(field: string): import('express').RequestHandler },
): void {
  const route = (handler: (req: SessionRequest, res: Response) => Promise<void>) => badRequestRoute(asyncRoute, handler);

  app.get(
    '/api/dotnet/context',
    requireSession,
    route(async (req, res) => {
      const session = req.session!;
      const [dotnet, ss] = await Promise.all([
        run(session, 'command -v dotnet >/dev/null 2>&1 && dotnet --list-runtimes 2>&1 || echo __missing__'),
        run(session, 'ss -Htln 2>/dev/null'),
      ]);
      const available = !dotnet.stdout.includes('__missing__');
      res.json({
        available,
        runtimes: available ? parseRuntimes(dotnet.stdout) : [],
        usedPorts: [...new Set([...ss.stdout.matchAll(/:(\d+)\s/g)].map((m) => Number(m[1])))],
      });
    }),
  );

  /** Uploads + unzips a publish bundle to a scratch directory and reports what it
   *  needs to run, mirroring /api/docker/image-info's "tell the wizard what it needs
   *  before asking for the rest" role. Nothing under /opt or /etc is touched yet. */
  app.post(
    '/api/dotnet/inspect',
    requireSession,
    upload.single('app'),
    route(async (req, res) => {
      const session = req.session!;
      const file = req.file;
      need(file, 'no app bundle uploaded');

      await cleanupOldStaging(session);

      const unzipCheck = await run(session, 'command -v unzip >/dev/null 2>&1 && echo yes || true');
      if (unzipCheck.stdout.trim() !== 'yes') {
        await fs.unlink(file.path).catch(() => {});
        need(false, 'unzip is required on this server to deploy a .NET app. Install it with: apt-get install -y unzip');
      }

      const stagingDir = `/tmp/ssher-dotnet-${randomUUID()}`;
      const remoteZip = `${stagingDir}.zip`;
      const transferId = str(req.body?.transferId) || randomUUID();
      const signal = startTransfer(transferId, file.size, { sessionId: session.id, label: file.originalname, processing: 'unzip' });
      try {
        await sftpUpload(session, file.path, remoteZip, { id: transferId, signal });
        copyFinished(transferId);
        const unzipped = await runCancellable(
          session,
          `mkdir -p ${shellQuote(stagingDir)} && unzip -o -q ${shellQuote(remoteZip)} -d ${shellQuote(stagingDir)} 2>&1`,
          signal,
        );
        need(unzipped.code === 0, (unzipped.stdout + unzipped.stderr).trim() || 'unzip failed');
        finishTransfer(transferId);

        const mainDll = await findMainDll(session, stagingDir);
        if (!mainDll) {
          await run(session, `rm -rf ${shellQuote(stagingDir)}`);
          need(false, 'Expected exactly one published app (one *.runtimeconfig.json) at the top level of the zip.');
        }

        const cfg = await readRuntimeConfig(session, stagingDir, mainDll);
        const selfContained = Boolean(cfg?.runtimeOptions?.includedFrameworks?.length);
        const required = cfg ? requiredFramework(cfg) : null;

        const runtimesOut = await run(session, 'command -v dotnet >/dev/null 2>&1 && dotnet --list-runtimes 2>&1 || echo __missing__');
        const dotnetAvailable = !runtimesOut.stdout.includes('__missing__');
        const installedRuntimes = dotnetAvailable ? parseRuntimes(runtimesOut.stdout) : [];
        const compatible =
          selfContained || !required || installedRuntimes.some((r) => r.name === required.name && isCompatible(r.version, required.version));

        const suggestedName = mainDll
          .replace(/\.dll$/, '')
          .toLowerCase()
          .replace(/[^a-z0-9_-]/g, '-')
          .slice(0, 40);

        res.json({
          ok: true,
          stagingDir,
          mainDll,
          suggestedName: suggestedName || 'app',
          selfContained,
          required,
          dotnetAvailable,
          installedRuntimes,
          compatible,
        });
      } catch (err) {
        finishTransfer(transferId, (err as Error).message);
        if (signal.aborted) await run(session, `rm -rf ${shellQuote(stagingDir)}`).catch(() => {});
        throw err;
      } finally {
        await fs.unlink(file.path).catch(() => {});
        await run(session, `rm -f ${shellQuote(remoteZip)}`).catch(() => {});
      }
    }),
  );

  app.post(
    '/api/dotnet/install-runtime',
    requireSession,
    route(async (req, res) => {
      const name = str(req.body?.name);
      const version = str(req.body?.version);
      need(/^\d+\.\d+(\.\d+)?$/.test(version), 'invalid runtime version');
      need(name === 'Microsoft.AspNetCore.App' || name === 'Microsoft.NETCore.App', 'invalid runtime name');
      const output = await runOrThrow(req.session!, `(${installCommand({ name, version })}) 2>&1`);
      res.json({ ok: true, output });
    }),
  );

  app.post(
    '/api/dotnet/deploy',
    requireSession,
    route(async (req, res) => {
      const session = req.session!;
      const stagingDir = str(req.body?.stagingDir);
      need(STAGING_RE.test(stagingDir), 'invalid or expired staging directory — drop the bundle again');
      const mainDll = str(req.body?.mainDll);
      need(/^[\w.-]+\.dll$/i.test(mainDll), 'invalid app dll name');

      const name = str(req.body?.name);
      need(RE.name.test(name), 'Name must be lowercase letters, digits, - or _');
      const appPort = port(req.body?.port, 'Port');
      const env = parseEnv(req.body?.env);
      const overwrite = Boolean(req.body?.overwrite);
      const domain = str(req.body?.domain).toLowerCase();
      for (const d of domain.split(/\s+/).filter(Boolean)) need(RE.domain.test(d), `Invalid domain: ${d}`);
      const maxBody = /^\d{1,4}[kmg]$/i.test(str(req.body?.maxBody)) ? str(req.body?.maxBody) : '100m';

      const dir = `/opt/${name}`;
      const log: StepResult[] = [];

      const staged = await run(session, `[ -d ${shellQuote(stagingDir)} ] && echo yes || true`);
      log.push({ title: 'Check the staged bundle is still there', ok: staged.stdout.trim() === 'yes', output: staged.stdout.trim() === 'yes' ? 'ok' : 'Gone — drop the bundle again.' });
      if (!log.at(-1)!.ok) {
        res.status(500).json({ error: log.at(-1)!.output, log });
        return;
      }

      const runtimeCheck = await checkRuntime(session, stagingDir, mainDll);
      log.push(runtimeCheck);
      if (!runtimeCheck.ok) {
        res.status(500).json({ error: runtimeCheck.output, log });
        return;
      }

      if (!overwrite) {
        const exists = await run(session, `[ -e ${shellQuote(dir)} ] && echo yes || true`);
        if (exists.stdout.trim() === 'yes') {
          const msg = `${dir} already exists — tick overwrite to replace it`;
          log.push({ title: 'Check the app directory is not already in use', ok: false, output: msg });
          res.status(500).json({ error: msg, log });
          return;
        }
      }

      const steps: Step[] = [
        {
          title: `Check port ${appPort} is free`,
          command: `if ss -Htln | awk '{print $4}' | grep -Eq ':${appPort}$'; then systemctl is-active --quiet ${shellQuote(name)} 2>/dev/null && echo "already used by ${name} itself" || { echo "Port ${appPort} is already in use on this server" >&2; exit 1; }; else echo free; fi`,
        },
        { title: 'Stop the previous version (if any)', command: `systemctl stop ${shellQuote(name)} 2>/dev/null; rm -rf ${shellQuote(dir)}; echo ok` },
        { title: `Move the app into ${dir}`, command: `mkdir -p /opt && cp -a ${shellQuote(stagingDir)} ${shellQuote(dir)} && rm -rf ${shellQuote(stagingDir)}` },
        {
          title: `Write ${posix.join(UNIT_DIR, `${name}.service`)}`,
          command: `tee ${shellQuote(posix.join(UNIT_DIR, `${name}.service`))} >/dev/null`,
          file: { path: posix.join(UNIT_DIR, `${name}.service`), content: renderUnit({ name, port: appPort, dir, mainDll, env }) },
        },
        { title: 'Reload systemd', command: 'systemctl daemon-reload' },
        { title: 'Enable and start the service', command: `systemctl enable --now ${shellQuote(name)} 2>&1` },
        { title: 'Check it is running', command: `systemctl --no-pager status ${shellQuote(name)} --lines=5 2>&1; true` },
      ];
      if (domain) {
        const content = renderNginxSite({ name, domain, target: `127.0.0.1:${appPort}`, maxBody });
        steps.push(...nginxSiteSteps(name, content));
      }

      const { log: rest, ok } = await runSteps(session, steps);
      log.push(...rest);
      if (!ok) {
        res.status(500).json({ error: `${rest.at(-1)!.title} failed`, log });
        return;
      }
      res.json({ ok: true, log, name, port: appPort, dir, url: domain ? `http://${domain.split(/\s+/)[0]}` : '' });
    }),
  );

  app.get(
    '/api/dotnet/apps',
    requireSession,
    route(async (req, res) => {
      const session = req.session!;
      const script = `for f in ${UNIT_DIR}/*.service; do [ -f "$f" ] || continue; grep -qF ${shellQuote(DOTNET_MARKER)} "$f" && basename "$f" .service; done`;
      const out = await run(session, script);
      const names = out.stdout.split('\n').map((l) => l.trim()).filter(Boolean);

      const apps = await Promise.all(
        names.map(async (name) => {
          const [unit, state] = await Promise.all([
            readFile(session, posix.join(UNIT_DIR, `${name}.service`)).catch(() => Buffer.from('')),
            run(session, `systemctl is-active ${shellQuote(name)} 2>/dev/null || true`),
          ]);
          const text = unit.toString('utf8');
          const portMatch = /--urls\s+http:\/\/127\.0\.0\.1:(\d+)/.exec(text)?.[1];
          const dirMatch = /^WorkingDirectory=(.*)$/m.exec(text)?.[1];
          return {
            name,
            state: state.stdout.trim() || 'unknown',
            port: Number(portMatch) || 0,
            dir: dirMatch || `/opt/${name}`,
          };
        }),
      );
      res.json({ apps });
    }),
  );

  app.post(
    '/api/dotnet/action',
    requireSession,
    route(async (req, res) => {
      const session = req.session!;
      const name = str(req.body?.name);
      need(RE.name.test(name), 'invalid app name');
      const action = str(req.body?.action);

      if (action === 'remove') {
        const dir = `/opt/${name}`;
        const unit = posix.join(UNIT_DIR, `${name}.service`);
        const content = await readFile(session, unit).catch(() => Buffer.from(''));
        need(content.toString('utf8').includes(DOTNET_MARKER), 'Only apps SSHer deployed can be removed here.');
        const output = await runOrThrow(
          session,
          `systemctl stop ${shellQuote(name)} 2>/dev/null; systemctl disable ${shellQuote(name)} 2>/dev/null; rm -f ${shellQuote(unit)}; systemctl daemon-reload; rm -rf ${shellQuote(dir)}; echo removed`,
        );
        res.json({ ok: true, output });
        return;
      }

      const commands: Record<string, string> = {
        start: `systemctl start ${shellQuote(name)}`,
        stop: `systemctl stop ${shellQuote(name)}`,
        restart: `systemctl restart ${shellQuote(name)}`,
      };
      need(commands[action], 'unknown action');
      const output = await runOrThrow(session, `${commands[action]} 2>&1`);
      res.json({ ok: true, output });
    }),
  );
}
